import boto3
import json


# ============================================================
# 1. Bedrock Runtime 클라이언트
# ============================================================

bedrock = boto3.client(
    service_name="bedrock-runtime",
    region_name="us-east-1"
)


# ============================================================
# 2. Amazon Nova Lite
#    US Cross-Region Inference Profile
# ============================================================

bedrock_model_id = "us.amazon.nova-lite-v1:0"


# ============================================================
# 3. 사용자 질문
# ============================================================

prompt = "What is the largest city in New Hampshire?"


# ============================================================
# 4. 메시지 작성
# ============================================================

messages = [
    {
        "role": "user",
        "content": [
            {
                "text": prompt
            }
        ]
    }
]


# ============================================================
# 5. 요청 Body
# ============================================================

body = json.dumps({
    "schemaVersion": "messages-v1",
    "messages": messages,
    "inferenceConfig": {
        "maxTokens": 1024,
        "topP": 0.5,
        "topK": 20,
        "temperature": 0.0
    }
})


# ============================================================
# 6. Bedrock 모델 호출
# ============================================================

response = bedrock.invoke_model(
    body=body,
    modelId=bedrock_model_id,
    accept="application/json",
    contentType="application/json"
)


# ============================================================
# 7. 응답 읽기
# ============================================================

response_body = json.loads(
    response["body"].read()
)


# ============================================================
# 8. 생성된 텍스트 가져오기
# ============================================================

response_text = (
    response_body["output"]["message"]["content"][0]["text"]
)


# ============================================================
# 9. 출력
# ============================================================

print(response_text)