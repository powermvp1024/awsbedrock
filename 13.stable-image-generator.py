# ============================================================
# Amazon Bedrock 이미지 생성 예제
# Stable Image Core + Python + boto3
# ============================================================
#
# [프로그램 동작 순서]
#
#  사용자 Prompt 입력
#        ↓
#  Python 프로그램
#        ↓
#  boto3
#        ↓
#  Amazon Bedrock Runtime
#        ↓
#  Stable Image Core 모델
#        ↓
#  이미지 생성
#        ↓
#  Base64 문자열로 이미지 반환
#        ↓
#  Base64 → 실제 이미지 데이터 변환
#        ↓
#  output/cat.png 파일 저장
#
# ============================================================


# ============================================================
# 01. 필요한 Python 라이브러리 불러오기
# ============================================================

# boto3
# ------------------------------------------------------------
# Python 프로그램에서 AWS 서비스를 사용하기 위한
# AWS 공식 Python SDK입니다.
#
# 예:
#   Python → S3
#   Python → EC2
#   Python → Lambda
#   Python → Bedrock
#
# 여기서는 Amazon Bedrock을 호출하기 위해 사용합니다.
# ------------------------------------------------------------

import boto3


# json
# ------------------------------------------------------------
# Python Dictionary 데이터를 JSON 형식으로 변환하거나
# JSON 데이터를 Python Dictionary로 변환할 때 사용합니다.
#
# Bedrock API에 요청할 때 JSON 형식의 데이터를 사용합니다.
# ------------------------------------------------------------

import json


# base64
# ------------------------------------------------------------
# Bedrock에서 생성된 이미지는 일반 PNG 파일 형태가 아니라
# Base64라는 문자열 형태로 전달됩니다.
#
# 따라서 Base64 문자열을 실제 이미지 데이터로
# 변환하기 위해 사용합니다.
# ------------------------------------------------------------

import base64


# random
# ------------------------------------------------------------
# 이미지 생성에 사용할 Seed 값을 무작위로 만들기 위해 사용합니다.
#
# Seed가 달라지면 같은 Prompt라도
# 조금씩 다른 이미지가 만들어질 수 있습니다.
# ------------------------------------------------------------

import random


# os
# ------------------------------------------------------------
# 폴더를 생성하거나 파일 경로를 만들 때 사용합니다.
#
# 여기서는 output 폴더를 자동으로 만드는 데 사용합니다.
# ------------------------------------------------------------

import os



# ============================================================
# 02. Amazon Bedrock Runtime Client 생성
# ============================================================
#
# boto3.client()
#
# Python 프로그램에서 AWS 서비스와 통신할 수 있는
# Client 객체를 생성합니다.
#
# 쉽게 생각하면:
#
# Python
#   ↓
# boto3 Client
#   ↓
# AWS Bedrock
#
# 형태입니다.
#
# service_name="bedrock-runtime"
#
# 실제 Foundation Model을 호출하는 서비스입니다.
#
# region_name="us-west-2"
#
# 사용할 AWS Region을 지정합니다.
#
# us-west-2 = 미국 서부 Oregon Region
#
# ============================================================

bedrock = boto3.client(
    service_name="bedrock-runtime",
    region_name="us-west-2"
)



# ============================================================
# 03. 사용할 Bedrock 모델 지정
# ============================================================
#
# Amazon Bedrock에는 여러 Foundation Model이 있습니다.
#
# 예:
#
# Amazon Nova
# Anthropic Claude
# Stability AI
# Meta Llama
# 등
#
# 여기서는 Stability AI의 Stable Image Core를 사용합니다.
#
# 이전에 사용했던
#
# amazon.titan-image-generator-v2:0
#
# 은 EOL(End of Life) 상태가 되어
# 현재 호출 시 오류가 발생할 수 있기 때문에
# Stable Image Core를 사용합니다.
#
# ============================================================

model_id = "stability.stable-image-core-v1:1"



# ============================================================
# 04. 생성할 이미지 설명 작성
# ============================================================
#
# Prompt란?
#
# AI에게 "어떤 이미지를 만들어 주세요."라고
# 설명하는 명령문입니다.
#
# 이미지 생성 모델은 일반적으로 영어 Prompt가
# 안정적인 결과를 만드는 데 유리합니다.
#
# 아래 Prompt는:
#
# "소파 위에 앉아 있는 귀여운 검은 고양이,
#  사실적인 사진,
#  부드러운 자연광,
#  고품질"
#
# 정도의 의미입니다.
#
# ============================================================

prompt = """
A cute black cat sitting on a sofa,
realistic photography,
soft natural lighting,
high quality
"""



# ============================================================
# 05. Seed 값 만들기
# ============================================================
#
# Seed란?
#
# 이미지 생성 과정에서 사용하는 일종의
# "랜덤 시작 번호"라고 이해하면 됩니다.
#
# 같은 Prompt라도 Seed 값이 달라지면
# 다른 이미지가 만들어질 수 있습니다.
#
# random.randint()
#
# 지정한 범위에서 임의의 정수를 하나 만듭니다.
#
# ============================================================

seed = random.randint(
    0,
    4294967295
)



# ============================================================
# 06. Bedrock에 전달할 요청 데이터 만들기
# ============================================================
#
# Python의 Dictionary 형태로 요청 데이터를 작성합니다.
#
# 이후 이 데이터를 JSON으로 변환해서
# Amazon Bedrock에 전달합니다.
#
# ============================================================

request_body = {

    # --------------------------------------------------------
    # prompt
    #
    # 어떤 이미지를 만들 것인지 설명합니다.
    # --------------------------------------------------------

    "prompt": prompt,


    # --------------------------------------------------------
    # aspect_ratio
    #
    # 이미지의 가로 : 세로 비율입니다.
    #
    # 1:1
    #
    # → 정사각형 이미지
    # --------------------------------------------------------

    "aspect_ratio": "1:1",


    # --------------------------------------------------------
    # seed
    #
    # 이미지 생성에 사용할 랜덤 시작값입니다.
    # --------------------------------------------------------

    "seed": seed,


    # --------------------------------------------------------
    # output_format
    #
    # 생성할 이미지 파일 형식을 지정합니다.
    #
    # png
    # jpeg
    # 등을 사용할 수 있습니다.
    # --------------------------------------------------------

    "output_format": "png"
}



# ============================================================
# 07. Python Dictionary → JSON 변환
# ============================================================
#
# 현재 request_body는 Python Dictionary입니다.
#
# 예:
#
# {
#     "prompt": "...",
#     "aspect_ratio": "1:1"
# }
#
# Bedrock API에는 JSON 형태로 전달해야 하므로
#
# json.dumps()
#
# 를 사용해서 JSON 문자열로 변환합니다.
#
# ============================================================

request = json.dumps(request_body)



# ============================================================
# 08. 사용자에게 진행 상태 출력
# ============================================================

print("======================================")
print("Amazon Bedrock 이미지 생성")
print("======================================")

print()

print("이미지를 생성하고 있습니다...")



# ============================================================
# 09. 예외 처리를 위한 try 시작
# ============================================================
#
# AWS API를 호출할 때는 여러 오류가 발생할 수 있습니다.
#
# 예:
#
# AWS 인증 오류
# IAM 권한 오류
# 모델 ID 오류
# Region 오류
# 네트워크 오류
#
# 프로그램이 바로 종료되지 않고 오류 내용을 보여주기 위해
# try / except를 사용합니다.
#
# ============================================================

try:


    # ========================================================
    # 10. Amazon Bedrock 모델 호출
    # ========================================================
    #
    # invoke_model()
    #
    # Bedrock Foundation Model을 직접 호출하는 API입니다.
    #
    # modelId
    #
    # → 어떤 모델을 사용할 것인지 지정
    #
    # body
    #
    # → 모델에게 전달할 Prompt 및 설정
    #
    # 전체 흐름:
    #
    # Python
    #    ↓
    # boto3
    #    ↓
    # invoke_model()
    #    ↓
    # Amazon Bedrock
    #    ↓
    # Stable Image Core
    #
    # ========================================================

    response = bedrock.invoke_model(

        modelId=model_id,

        body=request

    )



    # ========================================================
    # 11. Bedrock 응답 읽기
    # ========================================================
    #
    # Bedrock에서 받은 response에는 여러 정보가 들어 있습니다.
    #
    # 실제 모델의 결과는
    #
    # response["body"]
    #
    # 안에 있습니다.
    #
    # .read()
    #
    # 를 이용해서 데이터를 읽습니다.
    #
    # json.loads()
    #
    # 를 사용하여 JSON 데이터를
    # Python Dictionary로 변환합니다.
    #
    # ========================================================

    response_body = json.loads(
        response["body"].read()
    )



    # ========================================================
    # 12. 생성된 이미지 데이터 가져오기
    # ========================================================
    #
    # Stable Image Core의 응답에는
    # 생성된 이미지가 images 배열에 들어 있습니다.
    #
    # 대략 다음과 같은 구조입니다.
    #
    # {
    #     "images": [
    #         "iVBORw0KGgoAAA..."
    #     ]
    # }
    #
    # images[0]
    #
    # → 첫 번째 생성 이미지를 가져옵니다.
    #
    # 중요한 점:
    #
    # 이것은 아직 PNG 파일이 아닙니다.
    #
    # Base64로 인코딩된 문자열입니다.
    #
    # ========================================================

    base64_image = response_body["images"][0]



    # ========================================================
    # 13. Base64 → 실제 이미지 데이터 변환
    # ========================================================
    #
    # Bedrock
    #
    #       Base64 문자열
    #
    #              ↓
    #
    # base64.b64decode()
    #
    #              ↓
    #
    #       Binary 이미지 데이터
    #
    # 로 변환합니다.
    #
    # ========================================================

    image_data = base64.b64decode(
        base64_image
    )



    # ========================================================
    # 14. 이미지를 저장할 output 폴더 지정
    # ========================================================

    output_folder = "output"



    # ========================================================
    # 15. output 폴더 생성
    # ========================================================
    #
    # os.makedirs()
    #
    # 폴더가 없으면 새로 만듭니다.
    #
    # exist_ok=True
    #
    # 이미 output 폴더가 존재해도
    # 오류를 발생시키지 않습니다.
    #
    # ========================================================

    os.makedirs(
        output_folder,
        exist_ok=True
    )



    # ========================================================
    # 16. 저장할 이미지 파일 경로 만들기
    # ========================================================
    #
    # 결과:
    #
    # output\cat.png
    #
    # Windows에서 os.path.join()을 사용하면
    # 운영체제에 맞게 경로를 만들어 줍니다.
    #
    # ========================================================

    image_path = os.path.join(
        output_folder,
        "cat.png"
    )



    # ========================================================
    # 17. 실제 PNG 이미지 파일 저장
    # ========================================================
    #
    # open()
    #
    # 파일을 열거나 생성합니다.
    #
    # "wb"
    #
    # w = write
    # b = binary
    #
    # 즉,
    #
    # "Binary 데이터를 파일에 쓰겠다"
    #
    # 라는 의미입니다.
    #
    # 이미지 파일은 Binary 데이터이기 때문에
    # "wb"를 사용해야 합니다.
    #
    # ========================================================

    with open(image_path, "wb") as file:

        file.write(image_data)



    # ========================================================
    # 18. 이미지 생성 성공 메시지 출력
    # ========================================================

    print()

    print("======================================")
    print("이미지 생성 완료!")
    print("======================================")

    print()

    print("Prompt:")
    print(prompt)

    print("사용 모델:", model_id)

    print("Seed:", seed)

    print("저장 위치:", image_path)



# ============================================================
# 19. 오류가 발생했을 경우
# ============================================================
#
# try 부분에서 오류가 발생하면
# 아래 except 부분이 실행됩니다.
#
# ============================================================

except Exception as e:

    print()

    print("======================================")
    print("이미지 생성 오류")
    print("======================================")

    print()

    print(e)