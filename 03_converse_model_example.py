# ============================================================
# 02_converse_example.py
#
# Amazon Bedrock - Converse API 실습
# 모델: Amazon Nova Lite
#
# ============================================================
#
# [수업 목표]
#
# 1. Converse API의 목적을 이해합니다.
#
# 2. messages 기반의 대화 구조를 이해합니다.
#
# 3. InvokeModel과 달리 모델별 Native JSON을 직접
#    처리하는 부담을 줄여준다는 것을 이해합니다.
#
# 4. Chatbot / Multi-turn / Tool Use를 구현할 때
#    Converse가 왜 편리한지 이해합니다.
#
#
# [반드시 기억할 핵심]
#
# 사용자
#    ↓
# messages
#    ↓
# client.converse()
#    ↓
# Amazon Bedrock
#    ↓
# Foundation Model
#    ↓
# response["output"]["message"]
#    ↓
# AI 답변
#
#
# InvokeModel에서 사용했던:
#
# json.dumps()
# response["body"].read()
# json.loads()
#
# 같은 작업을 직접 할 필요가 없습니다.
#
# ============================================================


# ============================================================
# 0. 필요한 라이브러리 Import
# ============================================================

import os
import boto3

from dotenv import load_dotenv
from botocore.exceptions import ClientError, NoCredentialsError


# ============================================================
# [중요 강조 포인트 1]
#
# 여기에는 json 라이브러리가 없습니다.
#
# InvokeModel 예제:
#
# import json
#
# Converse 예제:
#
# json import 없음
#
#
# 이유:
#
# Converse에서는 boto3가 Converse API에 맞는
# Python 구조를 받아 요청/응답 직렬화를 처리하므로,
# 애플리케이션 코드에서 JSON 문자열을 직접 만들고
# 다시 파싱하는 과정이 필요하지 않습니다.
#
# 이것이 두 예제에서 눈에 보이는 차이 중 하나입니다.
#
# ============================================================


# ============================================================
# 1. .env 파일 읽기
# ============================================================

load_dotenv()


# ============================================================
# 2. AWS Region 설정
# ============================================================

region = os.getenv(
    "TEXT_REGION",
    "us-east-1"
)


# ============================================================
# 3. Model ID 설정
# ============================================================

model_id = os.getenv(
    "TEXT_MODEL_ID",
    "amazon.nova-lite-v1:0"
)


# ============================================================
# 4. 현재 설정 출력
# ============================================================

print("=" * 60)
print("02. Amazon Bedrock Converse API")
print("=" * 60)

print(f"AWS Region : {region}")
print(f"Model ID   : {model_id}")

print("=" * 60)


# ============================================================
# 5. Bedrock Runtime Client 생성
# ============================================================

client = boto3.client(
    "bedrock-runtime",
    region_name=region
)


# ============================================================
# [중요 강조 포인트 2]
#
# InvokeModel과 Converse 모두 동일한
#
# "bedrock-runtime"
#
# Client를 사용할 수 있습니다.
#
#
# 차이는 Client를 만든 다음 호출하는 메서드입니다.
#
#
# InvokeModel
#
# client.invoke_model()
#
#
# Converse
#
# client.converse()
#
#
# 따라서 두 API를 구분할 때 가장 먼저 확인할 부분은
#
# "어떤 메서드를 호출했는가?" 입니다.
#
# ============================================================


# ============================================================
# 6. 사용자 질문
# ============================================================

prompt = "AWS EC2 인스턴스 생성 전 확인할 항목을 3개로 알려줘."

print("\n[사용자 질문]")
print(prompt)


# ============================================================
# 7. Converse API 호출
# ============================================================

try:

    print("\nConverse API를 호출하고 있습니다...\n")

    response = client.converse(

        modelId=model_id,

        messages=[
            {
                "role": "user",

                "content": [
                    {
                        "text": prompt
                    }
                ]
            }
        ],

        inferenceConfig={

            "maxTokens": 300,

            "temperature": 0.3
        }
    )


    # ========================================================
    # ★★★★★ 중요 강조 포인트 3 - 가장 중요 ★★★★★
    #
    # Converse의 핵심은 messages입니다.
    #
    #
    # messages=[
    #     {
    #         "role": "user",
    #         "content": [
    #             {
    #                 "text": prompt
    #             }
    #         ]
    #     }
    # ]
    #
    #
    # 대화를:
    #
    # 누가 말했는가?
    #     → role
    #
    # 무엇을 말했는가?
    #     → content
    #
    # 로 표현합니다.
    #
    #
    # role="user"
    #
    #     사용자 메시지
    #
    #
    # role="assistant"
    #
    #     AI 모델 메시지
    #
    #
    # 따라서 대화가 여러 번 이어질 경우:
    #
    # user
    #   ↓
    # assistant
    #   ↓
    # user
    #   ↓
    # assistant
    #
    # 형태로 messages를 누적할 수 있습니다.
    # ========================================================
    # ★★★★★ 중요 강조 포인트 4 ★★★★★
    #
    # InvokeModel과 비교해 보세요.
    #
    #
    # InvokeModel:
    #
    # request_body = {...}
    #
    # body = json.dumps(request_body)
    #
    # response = client.invoke_model(
    #     body=body,
    #     ...
    # )
    #
    #
    # Converse:
    #
    # response = client.converse(
    #     messages=[...]
    # )
    #
    #
    # Converse에서는 애플리케이션 코드가
    # JSON 문자열을 직접 만들 필요가 없습니다.
    #
    # ========================================================


    # ========================================================
    # 8. AI 답변 추출
    # ========================================================

    answer = response[
        "output"
    ][
        "message"
    ][
        "content"
    ][0][
        "text"
    ]


    # ========================================================
    # ★★★★★ 중요 강조 포인트 5 ★★★★★
    #
    # Converse에서는:
    #
    # response["body"].read()
    #
    # json.loads()
    #
    # 를 직접 수행하지 않습니다.
    #
    #
    # 바로:
    #
    # response
    #    ↓
    # output
    #    ↓
    # message
    #    ↓
    # content
    #    ↓
    # text
    #
    # 로 접근할 수 있습니다.
    # ========================================================
    # 9. 결과 출력
    # ========================================================

    print("=" * 60)
    print("Converse 응답")
    print("=" * 60)

    print(answer)

    print("=" * 60)


    # ========================================================
    # 10. Stop Reason 확인
    # ========================================================

    print("\n[응답 정보]")

    print(
        "Stop Reason :",
        response.get("stopReason")
    )


    # ========================================================
    # ★★★★★ 중요 강조 포인트 6 ★★★★★
    #
    # stopReason은 모델이 왜 응답 생성을 중단했는지를
    # 알려주는 값입니다.
    #
    # 예:
    #
    # end_turn
    #
    #     현재 모델의 응답 턴이 정상적으로 끝남
    #
    #
    # tool_use
    #
    #     모델이 Tool 사용을 요청함
    #
    #
    # 특히 AI Agent를 만들 때 중요합니다.
    #
    #
    # 사용자:
    #
    # "서울 날씨 알려줘"
    #
    #           ↓
    #
    # Converse
    #
    #           ↓
    #
    # Nova 판단
    #
    # "날씨 Tool이 필요하다."
    #
    #           ↓
    #
    # stopReason = "tool_use"
    #
    #           ↓
    #
    # Python이 Lambda 실행
    #
    #           ↓
    #
    # Tool 결과를 Converse에 다시 전달
    #
    #           ↓
    #
    # 최종 자연어 답변
    #
    # ========================================================


    # ========================================================
    # 11. Token 사용량 확인
    # ========================================================

    print(
        "Token Usage :",
        response.get("usage")
    )


    # ========================================================
    # ★★★★★ 중요 강조 포인트 7 ★★★★★
    #
    # usage에는 모델 호출에 사용된 토큰 관련 정보가
    # 들어갑니다.
    #
    # 예:
    #
    # {
    #     "inputTokens": 20,
    #     "outputTokens": 100,
    #     "totalTokens": 120
    # }
    #
    #
    # inputTokens
    #
    #     모델에게 전달한 입력 토큰
    #
    #
    # outputTokens
    #
    #     모델이 생성한 출력 토큰
    #
    #
    # totalTokens
    #
    #     전체 토큰
    #
    #
    # 실제 서비스에서는 사용량과 비용을 관찰할 때
    # 중요한 정보가 됩니다.
    #
    # ========================================================


# ============================================================
# 12. AWS 인증 오류
# ============================================================

except NoCredentialsError:

    print("\n[AWS 인증 오류]")
    print("AWS 인증정보를 찾을 수 없습니다.")
    print("다음 명령으로 AWS 인증 상태를 확인하세요:")
    print("aws sts get-caller-identity")


# ============================================================
# 13. AWS Bedrock API 오류
# ============================================================

except ClientError as e:

    print("\n[AWS Bedrock 오류]")

    print(
        "Error Code    :",
        e.response["Error"]["Code"]
    )

    print(
        "Error Message :",
        e.response["Error"]["Message"]
    )


# ============================================================
# 14. 기타 오류
# ============================================================

except Exception as e:

    print("\n[프로그램 오류]")

    print("Error Type :", type(e).__name__)
    print("Message    :", str(e))